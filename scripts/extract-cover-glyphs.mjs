#!/usr/bin/env node
// ─────────────────────────────────────────────────────────────────────────────
// scripts/extract-cover-glyphs.mjs
//
// One-off helper: copies the SVG path data for the icons used on article
// covers out of lucide-react into src/lib/coverGlyphs.js, so the cover
// generator has no deep imports and runs the same in the browser and Node.
//
// Usage: node scripts/extract-cover-glyphs.mjs   (re-run after adding icons)
// ─────────────────────────────────────────────────────────────────────────────

import { writeFile } from 'node:fs/promises';
import { join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const REPO_ROOT = resolve(fileURLToPath(import.meta.url), '..', '..');
const OUT = join(REPO_ROOT, 'src', 'lib', 'coverGlyphs.js');
// lucide-react doesn't export per-icon subpaths, so load the files directly.
const ICON_DIR = join(REPO_ROOT, 'node_modules', 'lucide-react', 'dist', 'esm', 'icons');

const ICONS = [
  'shield', 'shield-alert', 'shield-check', 'lock-keyhole', 'lock', 'database', 'database-zap',
  'mail-warning', 'fish', 'bug', 'bug-off', 'triangle-alert', 'skull', 'biohazard', 'package',
  'boxes', 'network', 'router', 'cloud', 'cloud-cog', 'key-round', 'fingerprint', 'factory', 'zap',
  'cpu', 'microchip', 'server', 'server-cog', 'bot', 'brain', 'sparkles', 'brain-circuit',
  'landmark', 'scale', 'gavel', 'trending-up', 'chart-line', 'banknote', 'smartphone', 'globe',
  'eye', 'eye-off', 'rocket', 'satellite', 'satellite-dish', 'orbit', 'earth', 'telescope',
  'graduation-cap', 'award', 'book-open', 'atom', 'car', 'monitor', 'code', 'terminal', 'radar',
  'radio-tower', 'git-branch', 'file-warning', 'siren', 'wallet', 'bitcoin', 'badge-check', 'clipboard-check', 'trophy', 'notebook-pen',
];

const toKey = (name) => name.replace(/-([a-z])/g, (_, c) => c.toUpperCase());

const entries = [];
for (const name of ICONS) {
  const mod = await import(pathToFileURL(join(ICON_DIR, `${name}.js`)).href);
  const nodes = mod.__iconNode.map(([tag, attrs]) => {
    const { key, ...rest } = attrs;
    return [tag, rest];
  });
  entries.push(`  ${toKey(name)}: ${JSON.stringify(nodes)},`);
}

const src = `// Generated by scripts/extract-cover-glyphs.mjs. Do not edit by hand.
// Icon path data from Lucide (https://lucide.dev), ISC License,
// Copyright (c) Lucide Contributors. 24x24 viewBox, stroke-based.
export const glyphs = {
${entries.join('\n')}
};
`;
await writeFile(OUT, src, 'utf8');
console.log(`[extract-cover-glyphs] wrote ${ICONS.length} glyphs to src/lib/coverGlyphs.js`);
